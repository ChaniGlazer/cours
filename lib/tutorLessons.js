// הקשר טקסטואלי לפרומפט המערכת. title מגיע מ-D1 כשאין תקציר. topicKey (אם יש) מסמן איזה תרגיל הלומדת עובדת עליו.
export function lessonContext(courseId, lessonSlug, { title, topicKey } = {}) {
  const l = TUTOR_LESSONS[courseId]?.[lessonSlug];
  if (!l) return `שיעור: ${title || lessonSlug}\n(אין תקציר מפורט לשיעור הזה. התמקדי בנושא של הלומדת ובשיעור לפי הכותרת.)`;
  const lines = [`שיעור: ${l.title}`, `נושא: ${l.topic}`, "מושגי מפתח:"];
  for (const c of l.concepts) lines.push(`- ${c}`);
  lines.push("טעויות נפוצות:");
  for (const m of l.mistakes) lines.push(`- ${m}`);
  lines.push("תרגילי חובה (הרעיון והתשובה הם רק לשימושך, לבדיקת ההנמקה של הלומדת. לעולם לא לחשוף אותם כפתרון):");
  for (const e of l.exercises) {
    const mark = topicKey && e.id === topicKey ? " <- התרגיל שהיא עובדת עליו עכשיו" : "";
    lines.push(`- ${e.id}: ${e.task} | רעיון: ${e.idea} | תשובה: ${e.answer}${mark}`);
  }
  return lines.join("\n");
}
