export const SNAPSHOT = { date: "12.11.2026", openAnswers: 90 };

// ממצאים עיקריים, מחושבים חי מתוצאות הסקר (מבנה getSurveyResults: { total, counts }). הכרטיס האחרון נשען על מיון ידני של התשובות החופשיות (צילום מצב).
const pc = (n, total) => (total > 0 ? Math.round((n / total) * 100) : 0);
const sum = (obj, keys) => keys.reduce((s, k) => s + (obj?.[k] || 0), 0);

export function buildConclusions(results) {
  const total = results?.total || 0;
  const c = results?.counts || {};
  const daily = pc(sum(c.ai_usage, ["5"]), total);
  const manualYes = pc(sum(c.manual_first, ["yes"]), total);
  const manualStart = pc(sum(c.manual_first, ["start_only"]), total);
  const manualNo = pc(sum(c.manual_first, ["no"]), total);
  const arch = pc(sum(c.priorities, ["architecture"]), total);
  const review = pc(sum(c.priorities, ["review_ai"]), total);
  const syntax = pc(sum(c.priorities, ["syntax"]), total);
  const risk = pc(sum(c.junior_risk, ["4", "5"]), total);
  const riskMax = pc(sum(c.junior_risk, ["5"]), total);
  const riskLow = pc(sum(c.junior_risk, ["1", "2"]), total);
  return [
    {
      id: "daily_vs_manual",
      emoji: "⚡",
      pct: daily,
      title: "משתמשות ב-AI כל יום, ובכל זאת רוצות יסודות",
      text: `${daily}% משתמשות ב-AI בקוד כל יום. ועדיין ${manualYes + manualStart}% חושבות שצריך ללמוד לכתוב קוד ידנית לפני ה-AI: ${manualYes}% אמרו שחייבים, ועוד ${manualStart}% אמרו שלפחות בהתחלה. רק ${manualNo}% אמרו שאפשר ישר עם AI.`
    },
    {
      id: "architecture",
      emoji: "🏗️",
      pct: arch,
      title: "פחות תחביר, יותר ארכיטקטורה ובדיקה",
      text: `${arch}% בחרו ארכיטקטורה ותכנון בין שלושת הדברים החשובים ביותר ללמוד, ו-${review}% בחרו קריאה ובדיקה של קוד AI. תחביר ושפות? רק ${syntax}%. מה שחשוב היום הוא לא איך כותבים שורה, אלא מה בונים ואיך יודעים שהיא נכונה.`
    },
    {
      id: "juniors",
      emoji: "😰",
      pct: risk,
      title: "דאגה לדור הבא של המפתחים",
      text: `${risk}% חושבות שה-AI מסכן את העתיד של מפתחים בתחילת דרכם (די הרבה או מאוד), ו-${riskMax}% סימנו את הדאגה הגבוהה ביותר. רק ${riskLow}% לא חוששות בכלל או חוששות קצת.`
    },
    {
      id: "confidence",
      emoji: "💛",
      pct: 19,
      title: "מבן אדם מבקשים ביטחון, לא מידע",
      text: "בשאלה החופשית, 17 מתוך 90 כתבו על ביטחון, אמון או אחריות, ו-19 הזכירו במפורש בן אדם, מנטור או אנושיות. מה שה-AI לא נותן הוא לא ידע, אלא מישהו שאפשר לסמוך על דעתו, שיגיד כשטועים, ושייקח אחריות."
    }
  ];
}

